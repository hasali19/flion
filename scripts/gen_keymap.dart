// Generates crates/flion/src/keymap.rs from the key data used by Flutter's
// gen_keycodes tool (dev/tools/gen_keycodes in the Flutter SDK).
//
// Usage: dart scripts/gen_keymap.dart [path/to/flutter/sdk]
//
// If the SDK path is omitted, it is derived from the `dart` executable running
// this script, which works when using the dart bundled with Flutter.

import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final String sdkRoot = args.isNotEmpty ? args[0] : _sdkFromDart();
  final dataDir = Directory('$sdkRoot/dev/tools/gen_keycodes/data');

  if (!dataDir.existsSync()) {
    stderr.writeln('Could not find gen_keycodes data at ${dataDir.path}');
    stderr.writeln('Usage: dart scripts/gen_keymap.dart [path/to/flutter/sdk]');
    exit(1);
  }

  final physical = _readJson('${dataDir.path}/physical_key_data.g.json');
  final logical = _readJson('${dataDir.path}/logical_key_data.g.json');

  // xkb keycode -> (usb hid code, name)
  final physicalMap = _OutputMap('physical');
  for (final MapEntry(key: name, value: entry) in physical.entries) {
    final scanCodes = entry['scanCodes'] as Map<String, dynamic>;
    final xkb = scanCodes['xkb'] as int?;
    final usb = scanCodes['usb'] as int?;
    if (xkb != null && usb != null) {
      physicalMap.add(xkb, usb, name);
    }
  }

  // gtk keyval (= xkb keysym) -> (logical key, gtk name)
  final logicalMap = _OutputMap('logical');
  for (final entry in logical.values) {
    final gtkValues = (entry['values']?['gtk'] as List<dynamic>?) ?? [];
    final gtkNames = (entry['names']?['gtk'] as List<dynamic>?) ?? [];
    if (gtkValues.length != gtkNames.length) {
      throw StateError('Mismatched gtk names and values for ${entry['name']}');
    }
    for (var i = 0; i < gtkValues.length; i++) {
      logicalMap.add(
        gtkValues[i] as int,
        entry['value'] as int,
        gtkNames[i] as String,
      );
    }
  }

  final out = StringBuffer()
    ..writeln('// Generated by scripts/gen_keymap.dart')
    ..writeln()
    ..writeln(
      '/// Maps an xkb keycode (evdev scancode + 8) to a Flutter physical key.',
    )
    ..writeln('pub fn xkb_keycode_to_physical(keycode: u32) -> Option<u64> {')
    ..writeln('    Some(match keycode {')
    ..write(physicalMap.render(keyDigits: 8, valueDigits: 8))
    ..writeln('        _ => return None,')
    ..writeln('    })')
    ..writeln('}')
    ..writeln()
    ..writeln('/// Maps an xkb keysym to a Flutter logical key.')
    ..writeln('pub fn keysym_to_logical(keysym: u32) -> Option<u64> {')
    ..writeln('    Some(match keysym {')
    ..write(logicalMap.render(keyDigits: 8, valueDigits: 11))
    ..writeln('        _ => return None,')
    ..writeln('    })')
    ..writeln('}');

  final repoRoot = File.fromUri(Platform.script).parent.parent;
  final output = File('${repoRoot.path}/crates/flion/src/keymap.rs');
  output.writeAsStringSync(out.toString());

  print(
    'Wrote ${physicalMap.length} physical and ${logicalMap.length} logical '
    'entries to ${output.path}',
  );
}

String _sdkFromDart() {
  // <sdk>/bin/cache/dart-sdk/bin/dart
  return File(Platform.resolvedExecutable)
      .parent
      .parent
      .parent
      .parent
      .parent
      .path;
}

Map<String, dynamic> _readJson(String path) =>
    jsonDecode(File(path).readAsStringSync()) as Map<String, dynamic>;

/// Like gen_keycodes' OutputLines: entries are sorted by key, and the first
/// entry for a duplicate key wins.
class _OutputMap {
  _OutputMap(this.name);

  final String name;
  final Map<int, (int, String)> _entries = {};

  int get length => _entries.length;

  void add(int key, int value, String comment) {
    final existing = _entries[key];
    if (existing != null) {
      stderr.writeln(
        'Warn: duplicate key ${_hex(key, 8)} in $name map: '
        '"$comment" ignored in favour of "${existing.$2}"',
      );
      return;
    }
    _entries[key] = (value, comment);
  }

  String render({required int keyDigits, required int valueDigits}) {
    final keys = _entries.keys.toList()..sort();
    final buffer = StringBuffer();
    for (final key in keys) {
      final (value, comment) = _entries[key]!;
      buffer.writeln(
        '        ${_hex(key, keyDigits)} => ${_hex(value, valueDigits)}, // $comment',
      );
    }
    return buffer.toString();
  }
}

String _hex(int n, int digits) =>
    '0x${n.toRadixString(16).padLeft(digits, '0')}';
